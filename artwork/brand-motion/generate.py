def make_state(kind,art):
    config=STATE_POSES[kind];end=config['end'];eyes=[] if config.get('closed_eyes') else config['eyes']
    moving_prop=not config.get('static_prop')
    prop_points=config['points']
    layers=[]
    # Small backing patches prevent cutout gaps when the held prop pivots.
    if moving_prop:
        layers.append(layer('Clothing behind prop',[group('Backing',[shape(prop_points)],config['backing'])]))
    for i,points in enumerate(eyes):
        layers.append(layer('Skin behind eye '+str(i),[group('Peach eyelid',[shape(points)],'#FFE7DA')]))
    masks=[mask('Full state pose',[[0,0],[512,0],[512,512],[0,512]])]
    for i,points in enumerate(eyes):masks.append(mask('Eye '+str(i),points,'s'))
    if moving_prop:masks.append(mask('Held prop',prop_points,'s'))
    for i,points in enumerate(config['hair']):masks.append(mask('Hair tip '+str(i),points,'s'))
    layers.append(layer('Distinct '+kind+' pose' if moving_prop else config['prop'],ref='maid_art',masks=masks))
    if moving_prop:
        layers.append(layer(config['prop'],ref='maid_art',pivot=config['pivot'],masks=[mask('Hand and prop',prop_points)],rotation=keys(config['rotation']),scale=keys(config['scale']) if 'scale' in config else None))
    close=config.get('blink_frame',67)
    for i,points in enumerate(eyes):
        name=config.get('eye_names',['Left','Right'])[i]+' eye'
        layers.append(layer(name,ref='maid_art',pivot=bounds_center(points),masks=[mask(name,points)],
            scale=keys([(0,[100,100,100]),(close-5,[100,100,100]),(close,[100,4,100]),(close+6,[100,100,100]),(end,[100,100,100])])))
        layers.append(closed_eyelash(name,points,end,close))
    for i,points in enumerate(config['hair']):
        pivot=[bounds_center(points)[0],min(p[1] for p in points)]
        layers.append(layer('Hair tip '+str(i),ref='maid_art',pivot=pivot,masks=[mask('Hair',points)],
            rotation=keys([(0,0),(end*.4,-.9 if i==0 else .9),(end,0)])))
    if kind=='retry':
        layers.append(layer('Disconnected gap hint',[group('Paused connection',[shape([[256,325],[269,325]],False)],None,'#6CA6CB',2)],
            opacity=keys([(0,0),(16,0),(27,75),(40,0),(end,0)])))
    elif kind=='empty':
        layers.append(layer('Empty box glint',[group('Snow glint',[star(0,0,3)],'#FFFFFF')],
            position=keys([(0,[240,417,0]),(32,[240,417,0]),(54,[273,421,0]),(end,[273,421,0])]),
            opacity=keys([(0,0),(32,0),(42,65),(54,0),(end,0)])))
    elif kind=='favorite':
        layers.append(layer('Favorite star shimmer',[group('Star shimmer',[star(0,0,6)],'#FFFFFF','#FFE69A',1)],
            position=keys([(0,[254,306,0]),(end,[261,298,0])]),opacity=keys([(0,0),(16,0),(28,90),(44,0),(end,0)])))
    elif kind=='download':
        layers.append(layer('Saved video check pulse',[group('Completion ring',[ellipse(0,0,36,36)],None,'#6FCBEE',2)],
            pivot=(0,0),position=prop([364,387,0]),scale=keys([(0,[90,90,100]),(20,[90,90,100]),(37,[118,118,100]),(end,[125,125,100])]),
            opacity=keys([(0,0),(20,0),(29,70),(48,0),(end,0)])))
    else:
        layers.append(layer('Lens inspection glint',[group('Glass glint',[ellipse(0,0,3,8)],'#FFFFFF')],
            position=keys([(0,[195,207,0]),(22,[195,207,0]),(46,[237,201,0]),(end,[237,201,0])]),
            opacity=keys([(0,0),(22,0),(31,65),(46,0),(end,0)])))
    layers.reverse()
    motion=layer('State breathing and head tilt',pivot=(256,300));motion['ty']=3;motion.pop('shapes',None);motion['ind']=len(layers)+1
    motion['ks']['p']=keys([(0,[256,300,0]),(end*.5,[256,302,0]),(end,[256,300,0])])
    motion['ks']['r']=keys([(0,0),(end*.4,.4 if kind=='retry' else -.4),(end,0)])
    for i,l in enumerate(layers):l['ind']=i+1;l['op']=end;l['parent']=motion['ind']
    motion['op']=end;layers.append(motion)
    return {'v':'5.12.2','fr':60,'ip':0,'op':end,'w':512,'h':512,'nm':'BiliPai distinct '+kind+' pose','ddd':0,'assets':copy.deepcopy(art),'layers':layers,'markers':[]}


