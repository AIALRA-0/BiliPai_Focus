def prop(v): return {'a':0,'k':v}
def keys(values):
    out=[]
    for j,(t,v) in enumerate(values):
        d={'t':t,'s':v if isinstance(v,list) else [v]}
        if j<len(values)-1:
            end=values[j+1][1]
            d.update(e=end if isinstance(end,list) else [end],o={'x':[.23],'y':[1]},i={'x':[.32],'y':[1]})
        out.append(d)
    return {'a':1,'k':out}
def color(h): return [int(h[i:i+2],16)/255 for i in (1,3,5)]+[1]
def xy(z): return [round(z.real,2),round(z.imag,2)]
def transform(): return {'ty':'tr','p':prop([0,0]),'a':prop([0,0]),'s':prop([100,100]),'r':prop(0),'o':prop(100),'sk':prop(0),'sa':prop(0)}
def group(name,geometries,fill=None,stroke=None,width=2):
    it=list(geometries)
    if fill: it.append({'ty':'fl','c':prop(color(fill)),'o':prop(100),'r':1})
    if stroke: it.append({'ty':'st','c':prop(color(stroke)),'o':prop(100),'w':prop(width),'lc':2,'lj':2})
    it.append(transform()); return {'ty':'gr','nm':name,'it':it}
def poly(points,closed=True):
    return {'v':points,'i':[[0,0] for _ in points],'o':[[0,0] for _ in points],'c':closed}
def shape(points,closed=True): return {'ty':'sh','ks':prop(poly(points,closed))}
def ellipse(x,y,w,h): return {'ty':'el','p':prop([x,y]),'s':prop([w,h]),'d':1}
def rect(x,y,w,h,r=6): return {'ty':'rc','p':prop([x,y]),'s':prop([w,h]),'r':prop(r),'d':1}

def layer(name,shapes=(),pivot=(0,0),rotation=None,scale=None,position=None,opacity=None,ref=None,masks=()):
    l={'ddd':0,'ind':0,'ty':0 if ref else 4,'nm':name,'sr':1,'ks':{'o':opacity or prop(100),'r':rotation or prop(0),'p':position or prop([*pivot,0]),'a':prop([*pivot,0]),'s':scale or prop([100,100,100])},'ao':0,'ip':0,'op':144,'st':0,'bm':0}
    if ref: l.update(refId=ref,w=512,h=512)
    else: l['shapes']=list(reversed(shapes))
    if masks: l['masksProperties']=list(masks); l['hasMask']=True
    return l

def mask(name,points,mode='a'):
    return {'inv':False,'mode':mode,'pt':prop(poly(points)),'o':prop(100),'x':prop(0),'nm':name}
def mapped(points): return [[round(x*450/1349+62,2),round(y*450/1349+31,2)] for x,y in points]
def bounds_center(points): return [(min(p[0] for p in points)+max(p[0] for p in points))/2,(min(p[1] for p in points)+max(p[1] for p in points))/2]
def star(x,y,r): return shape([[x,y-r],[x+r*.28,y-r*.28],[x+r,y],[x+r*.28,y+r*.28],[x,y+r],[x-r*.28,y+r*.28],[x-r,y],[x-r*.28,y-r*.28]])

def closed_eyelash(name,points,end,close_frame=None):
    x,y=bounds_center(points)
    reach=min(17,(max(p[0] for p in points)-min(p[0] for p in points))/3)
    curve={'ty':'sh','ks':prop({'v':[[x-reach,y],[x,y+2],[x+reach,y]],
        'i':[[0,0],[-3,0],[-3,1]],'o':[[3,1],[3,0],[0,0]],'c':False})}
    opacity=keys([(0,100),(3,100),(8,0),(end,0)]) if close_frame is None else keys([
        (0,0),(close_frame-3,0),(close_frame,100),(close_frame+2,100),(close_frame+6,0),(end,0)])
    return layer(name+' closed eyelash',[group('Soft closed eye',[curve],None,'#80566A',1.8)],opacity=opacity)

def load_art(source='blue-snow-maid-reference.png',static='bilipai_maid_static',size=(390,450)):
    im=Image.open(ART/source).convert('RGBA')
    im.thumbnail(size,Image.Resampling.LANCZOS)
    canvas=Image.new('RGBA',(512,512))
    canvas.alpha_composite(im,((512-im.width)//2,31))
    target=ROOT/'brand-motion/src/main/res/drawable-nodpi'/f'{static}.webp'
    target.parent.mkdir(parents=True,exist_ok=True)
    import io
    buffer = io.BytesIO()
    canvas.save(buffer, format='PNG', optimize=True)
    target.write_bytes(encode_lossless_webp(buffer.getvalue()))
    image={'id':'maid_bitmap','w':512,'h':512,'u':'','p':static+'.webp','e':0}
    art=layer('Blue snow maid detailed illustration',ref='maid_bitmap')
    art['ty']=2; art['ind']=1
    return [{'id':'maid_art','layers':[art]},image]

