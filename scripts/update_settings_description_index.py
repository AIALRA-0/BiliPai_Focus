import re,json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
base=root/'app/src/main/java/com/android/purebilibili/feature/settings'
# Tokenizing keeps braces and commas inside strings/comments out of scope matching.
pattern=re.compile(r'"""[\s\S]*?"""|"(?:\\.|[^"\\])*"|//[^\n]*|/\*[\s\S]*?\*/|[{}(),]|[^{}(),"/]+|.',re.S)
def expr_end(text,start):
 depth=0
 for t in pattern.finditer(text,start):
  v=t.group()
  if v in '({':depth+=1
  elif v in ')}':
   if depth==0:return t.start()
   depth-=1
  elif v==',' and depth==0:return t.start()
 return len(text)
def literal(v):
 if '$' in v:return ''
 try:return json.loads(v)
 except Exception:return ''
entries={}; unresolved=[]
for p in sorted(base.rglob('*.kt')):
 if p.name.startswith('SettingsDescription'):continue
 s=p.read_text()
 for m in re.finditer(r'SettingsItemAnchor\("([^"]+)"\)\s*\{',s):
  start=m.end();depth=1;end=len(s)
  for t in pattern.finditer(s,start):
   if t.group()=='{':depth+=1
   elif t.group()=='}':
    depth-=1
    if depth==0:end=t.start();break
  block=s[start:end];parts=[]
  for d in re.finditer(r'\bsubtitle\s*=\s*',block):
   expr=block[d.end():expr_end(block,d.end())]
   strings=[literal(t.group()) for t in pattern.finditer(expr) if t.group().startswith('"')]
   parts.extend(x for x in strings if x)
   if not strings:unresolved.append((m[1],expr.strip().replace('\n',' ')[:95]))
  if parts:entries.setdefault(m[1],[]).extend(parts)
out=base/'SettingsDescriptionIndex.kt'
lines=['package com.android.purebilibili.feature.settings','', '// Generated by scripts/update_settings_description_index.py from SettingsItemAnchor subtitles.', 'internal val settingsStaticDescriptionIndex: Map<String, String> = mapOf(']
for key,parts in sorted(entries.items()):
 desc='；'.join(dict.fromkeys(parts))
 lines.append('    '+json.dumps(key,ensure_ascii=False)+' to '+json.dumps(desc,ensure_ascii=False).replace('$','\\$')+',')
lines+=[')'];out.write_text('\n'.join(lines)+'\n')
print('已收录说明',len(entries),'项')
for item in unresolved:print(*item,sep=': ')
